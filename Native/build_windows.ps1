<#
Builds Native/bin/win64/vbhost.dll (+ vbhost.lib) on Windows with the portable llvm-mingw toolchain.
Toolchain (as last used): llvm-mingw 20261006 ucrt-x86_64 (clang 23.1.3, lld, libc++), from
  https://github.com/mstorsjo/llvm-mingw/releases  (sha256 317492c456aa27ee607a5919f1d2d38dcdc1112516a24d0bf4b00d078f52d17a)
unzipped to <repo>\tools\llvm-mingw (or point $env:VB_MINGW at any llvm-mingw root), and
  SDL2 2.32.10 mingw devel build (SDL2-devel-2.32.10-mingw.zip from libsdl-org/SDL, sha256
  f15cff5fca62ec9381a016ef1d42a95c638cd72d2f226ba5781c76fe43dbd1ac) unzipped to <repo>\tools\SDL2-2.32.10
  (or point $env:SDL2_MINGW at its x86_64-w64-mingw32 folder). <repo> is the main checkout, the folder
  that holds .git (a git worktree shares its tools folder with it).
SDL2 and the C++ runtime are linked statically; only system DLLs remain as imports.
The DLL carries a VERSIONINFO resource (Native\host\vbhost.rc, compiled with llvm-windres). Its
ProductVersion is the editor version read from VisualBeefCore\src\Document\CommandLine.bf (Version), the
same source scripts\package.ps1 uses, and its company and copyright come from NOTICE. The script writes
them into obj\win64\vbversion.h before it compiles the resource.
Usage: powershell -File Native\build_windows.ps1 [-Clean]
The older Native/build_windows_mingw.sh (MSYS/Linux mingw-w64 g++) still works too.
#>
param([switch]$Clean)
$ErrorActionPreference = 'Stop'
$here = $PSScriptRoot
$root = Split-Path $here -Parent
$tools = Join-Path (Split-Path (git -C $here rev-parse --path-format=absolute --git-common-dir) -Parent) 'tools'  # absolute: from the main tree the plain form returns the relative '.git'
$mingw = if ($env:VB_MINGW) { $env:VB_MINGW } else { Join-Path $tools 'llvm-mingw' }
if (-not (Test-Path (Join-Path $mingw 'bin\clang++.exe'))) {
  throw "llvm-mingw not found at '$mingw'. Unzip llvm-mingw-<date>-ucrt-x86_64.zip there or set VB_MINGW (see the header of this script)."
}
$sdl = if ($env:SDL2_MINGW) { $env:SDL2_MINGW } else { Join-Path $tools 'SDL2-2.32.10\x86_64-w64-mingw32' }
if (-not (Test-Path (Join-Path $sdl 'lib\libSDL2.a'))) {
  throw "SDL2 mingw devel not found at '$sdl'. Set SDL2_MINGW to its x86_64-w64-mingw32 folder (see the header of this script)."
}
$bin = Join-Path $mingw 'bin'
$cxx = Join-Path $bin 'clang++.exe'
$T = Join-Path $here 'third_party'
$out = Join-Path $here 'bin\win64'
$obj = Join-Path $here 'obj\win64'
New-Item -ItemType Directory -Force $out, $obj | Out-Null
if ($Clean) { Get-ChildItem $obj -Filter *.o | Remove-Item }

# VERSIONINFO inputs: the editor version (the same constant scripts\package.ps1 stamps on the exe) and the
# copyright holder and line from NOTICE (the exe takes them from the same file via BeefProj's [Platform.Windows]).
$repoRoot = Split-Path $here -Parent
$cmdInfo = [IO.File]::ReadAllText((Join-Path $repoRoot 'VisualBeefCore\src\Document\CommandLine.bf'))
if ($cmdInfo -notmatch 'public const String Version = "(\d+)\.(\d+)\.(\d+)";') { throw 'VisualBeefInfo.Version (major.minor.patch) not found in CommandLine.bf' }
$verMajor, $verMinor, $verPatch = $Matches[1], $Matches[2], $Matches[3]
$noticeText = [IO.File]::ReadAllText((Join-Path $repoRoot 'NOTICE'))
if ($noticeText -notmatch '(?m)^(Copyright\s+\d{4}\s+.+?)\s*$') { throw 'NOTICE has no Copyright line' }
$copyrightLine = $Matches[1]
$holder = $copyrightLine -replace '^Copyright\s+\d{4}\s+', ''
$gen = @(
  "/* Generated by Native\build_windows.ps1 from CommandLine.bf and NOTICE. Do not edit. */",
  "#define VB_VER_MAJOR $verMajor",
  "#define VB_VER_MINOR $verMinor",
  "#define VB_VER_PATCH $verPatch",
  "#define VB_VER_STR `"$verMajor.$verMinor.$verPatch`"",
  "#define VB_FILE_VERSION_STR `"$verMajor.$verMinor.$verPatch.0`"",
  "#define VB_COMPANY `"$holder`"",
  "#define VB_COPYRIGHT `"$copyrightLine`""
)
Set-Content -Path (Join-Path $obj 'vbversion.h') -Value $gen -Encoding ascii
$srcs = @(
  'cimgui\imgui\imgui.cpp','cimgui\imgui\imgui_draw.cpp','cimgui\imgui\imgui_tables.cpp','cimgui\imgui\imgui_widgets.cpp',
  'cimgui\imgui\imgui_demo.cpp','cimgui\imgui\imgui_impl_sdl2.cpp','cimgui\imgui\imgui_impl_opengl3.cpp',
  'cimgui\cimgui.cpp','cimnodes\imnodes\imnodes.cpp','cimnodes\cimnodes.cpp') | ForEach-Object { Join-Path $T $_ }
$srcs += Join-Path $here 'host\vbhost.cpp'
# Embedded __FILE__ strings (ImGui asserts) name the source relative to the repository, not the build machine.
$flags = @('-O2','-DNDEBUG','-DIMNODES_NAMESPACE=imnodes','-DSDL_MAIN_HANDLED',"-ffile-prefix-map=$root=.","-ffile-prefix-map=$($root.Replace([char]92,[char]47))=.","-I$T\cimgui\imgui","-I$T\cimgui","-I$T\cimnodes\imnodes","-I$sdl\include\SDL2")
$objs = @()
foreach ($s in $srcs) {
  $o = Join-Path $obj (([IO.Path]::GetFileNameWithoutExtension($s)) + '.o')
  if (-not (Test-Path $o) -or (Get-Item $s).LastWriteTime -gt (Get-Item $o).LastWriteTime) {
    Write-Host "  CXX $s"
    & $cxx @flags -c $s -o $o
    if ($LASTEXITCODE) { throw "compile failed: $s" }
  }
  $objs += $o
}
# VERSIONINFO resource (Native\host\vbhost.rc + the generated vbversion.h).
$resObj = Join-Path $obj 'vbhost.res.o'
& (Join-Path $bin 'llvm-windres.exe') -I $obj -I (Join-Path $here 'host') -O coff (Join-Path $here 'host\vbhost.rc') -o $resObj
if ($LASTEXITCODE) { throw 'windres failed: host\vbhost.rc' }
$objs += $resObj
$libs = @('-lopengl32','-lsetupapi','-lwinmm','-limm32','-lversion','-lole32','-loleaut32','-lgdi32','-luser32','-lshell32','-luuid','-ladvapi32','-lcfgmgr32')
& $cxx -shared -o "$out\vbhost.dll" @objs "-Wl,--output-def,$out\vbhost.def" -s -static "$sdl\lib\libSDL2.a" @libs
if ($LASTEXITCODE) { throw 'link failed' }
# MSVC-compatible import library so Beef (lld-link) can link against the DLL.
& (Join-Path $bin 'llvm-dlltool.exe') -m i386:x86-64 -d "$out\vbhost.def" -D vbhost.dll -l "$out\vbhost.lib"
if ($LASTEXITCODE) { throw 'dlltool failed' }
Write-Host "Built $out\vbhost.dll + vbhost.lib"
